// Copie bizzi-db (Neon, Oregon) -> zeyds-prod (Neon, Francfort) : structure puis donnees.
// Usage : node copy-neon.mjs schema   (une fois, base cible vide)
//         node copy-neon.mjs data     (rejouable : vide les tables cibles puis recopie)
//         node copy-neon.mjs verify   (compare les nombres de lignes)
import fs from "node:fs";
import pg from "pg";

const env = Object.fromEntries(
  fs.readFileSync(new URL("./.env", import.meta.url), "utf8").split(/\r?\n/).filter(Boolean).map((l) => {
    const i = l.indexOf("=");
    return [l.slice(0, i), l.slice(i + 1)];
  }),
);
const EXCLUDED_TABLES = new Set(["playing_with_neon"]); // table de demo Neon
const mode = process.argv[2];

async function connect(url) {
  const client = new pg.Client({ connectionString: url, ssl: { rejectUnauthorized: true } });
  await client.connect();
  return client;
}

const DDL_SQL = `
with rels as (
  select c.oid, c.relname, c.relkind, c.relrowsecurity, c.reloptions
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relname <> all($1::text[])
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
), stmts as (
  select 1 as grp, t.typname::text as k, 'create type public.' || quote_ident(t.typname) || ' as enum ('
    || string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) || ');' as sql
  from pg_type t join pg_namespace n on n.oid = t.typnamespace join pg_enum e on e.enumtypid = t.oid
  where n.nspname = 'public' group by t.typname
  union all
  select 2, r.relname, 'create table public.' || quote_ident(r.relname) || E' (\\n  ' || string_agg(
      quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
      || case when a.attidentity = 'a' then ' generated always as identity'
              when a.attidentity = 'd' then ' generated by default as identity'
              when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
              when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end
      || case when a.attnotnull then ' not null' else '' end, E',\\n  ' order by a.attnum) || E'\\n);'
  from rels r join pg_attribute a on a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  where r.relkind in ('r', 'p') group by r.relname
  union all
  select case when con.contype = 'f' then 20 else 3 end, r.relname || '.' || con.conname,
    'alter table public.' || quote_ident(r.relname) || ' add constraint ' || quote_ident(con.conname) || ' ' || pg_get_constraintdef(con.oid) || ';'
  from pg_constraint con join rels r on r.oid = con.conrelid where con.contype in ('p', 'u', 'c', 'f', 'x')
  union all
  select 5, i.relname, pg_get_indexdef(i.oid) || ';'
  from pg_index x join pg_class i on i.oid = x.indexrelid join rels r on r.oid = x.indrelid
  where not exists (select 1 from pg_constraint c where c.conindid = x.indexrelid)
  union all
  select 6, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')', pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  union all
  select 7, r.relname, 'create or replace view public.' || quote_ident(r.relname)
    || coalesce(' with (' || array_to_string(r.reloptions, ', ') || ')', '') || E' as\\n' || pg_get_viewdef(r.oid, true)
  from rels r where r.relkind = 'v'
  union all
  select 21, r.relname || '.' || t.tgname, pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t join rels r on r.oid = t.tgrelid where not t.tgisinternal
  union all
  select 9, r.relname, 'alter table public.' || quote_ident(r.relname) || ' enable row level security;' from rels r where r.relrowsecurity
  union all
  select 10, pol.tablename || '.' || pol.policyname,
    'create policy ' || quote_ident(pol.policyname) || ' on public.' || quote_ident(pol.tablename)
    || ' as ' || lower(pol.permissive) || ' for ' || lower(pol.cmd) || ' to ' || array_to_string(pol.roles, ', ')
    || coalesce(' using (' || pol.qual || ')', '') || coalesce(' with check (' || pol.with_check || ')', '') || ';'
  from pg_policies pol where pol.schemaname = 'public' and pol.tablename <> all($1::text[])
  union all
  select 11, c.relname || '.' || ro.rolname,
    'grant ' || string_agg(distinct a.privilege_type, ', ') || ' on public.' || quote_ident(c.relname) || ' to ' || ro.rolname || ';'
  from rels c cross join lateral aclexplode(
    (select relacl from pg_class where oid = c.oid)) a join pg_roles ro on ro.oid = a.grantee
  where ro.rolname in ('anon', 'authenticated', 'service_role') group by c.relname, ro.rolname
  union all
  select 12, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
    'revoke execute on function public.' || quote_ident(p.proname) || '(' || pg_get_function_identity_arguments(p.oid) || ') from public;'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.proacl is not null and not exists (select 1 from aclexplode(p.proacl) a where a.grantee = 0)
  union all
  select 13, p.proname || '.' || ro.rolname,
    'grant execute on function public.' || quote_ident(p.proname) || '(' || pg_get_function_identity_arguments(p.oid) || ') to ' || ro.rolname || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  cross join lateral aclexplode(p.proacl) a join pg_roles ro on ro.oid = a.grantee
  where n.nspname = 'public' and ro.rolname in ('anon', 'authenticated', 'service_role') and a.privilege_type = 'EXECUTE'
)
select grp, k, sql from stmts order by grp, k`;

const PRELUDE = [
  "do $$ begin create role anon nologin noinherit; exception when duplicate_object then null; end $$;",
  "do $$ begin create role authenticated nologin noinherit; exception when duplicate_object then null; end $$;",
  "do $$ begin create role service_role nologin noinherit bypassrls; exception when duplicate_object then null; when insufficient_privilege then create role service_role nologin noinherit; end $$;",
  "do $$ begin create role postgres nologin noinherit; exception when duplicate_object then null; end $$;",
  "grant anon, authenticated, service_role to neondb_owner;",
  "create schema if not exists extensions;",
  "create schema if not exists auth;",
  'create extension if not exists "uuid-ossp" with schema extensions;',
  "create extension if not exists pgcrypto with schema extensions;",
  "create extension if not exists pg_trgm with schema extensions;",
  "create extension if not exists postgis with schema extensions;",
  "create or replace function auth.uid() returns uuid language sql stable as $f$ select null::uuid $f$;",
  "create or replace function auth.role() returns text language sql stable as $f$ select 'anon'::text $f$;",
  "grant usage on schema public to anon, authenticated, service_role;",
];

async function runPasses(client, statements, label) {
  let pending = statements;
  for (let pass = 1; pending.length && pass <= 6; pass += 1) {
    const failed = [];
    for (const st of pending) {
      try {
        await client.query(st.sql);
      } catch (error) {
        failed.push({ ...st, error: error.message });
      }
    }
    console.log(`${label} passe ${pass} : ${pending.length - failed.length} ok, ${failed.length} en echec`);
    if (failed.length === pending.length) {
      pending = failed;
      break;
    }
    pending = failed;
  }
  return pending;
}

async function tables(client) {
  const { rows } = await client.query(
    `select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind = 'r' and c.relname <> all($1::text[]) order by 1`,
    [[...EXCLUDED_TABLES]],
  );
  return rows.map((r) => r.relname);
}

async function columns(client, table) {
  const { rows } = await client.query(
    `select a.attname, format_type(a.atttypid, a.atttypmod) as type, a.attidentity
     from pg_attribute a where a.attrelid = ('public.' || quote_ident($1))::regclass
       and a.attnum > 0 and not a.attisdropped and a.attgenerated = '' order by a.attnum`,
    [table],
  );
  return rows;
}

const q = (name) => '"' + name.replace(/"/g, '""') + '"';

async function schema() {
  const [src, tgt] = [await connect(env.SOURCE_URL), await connect(env.TARGET_URL)];
  for (const sql of PRELUDE) await tgt.query(sql);
  const { rows } = await src.query(DDL_SQL, [[...EXCLUDED_TABLES]]);
  const before = rows.filter((r) => r.grp < 20);
  const after = rows.filter((r) => r.grp >= 20);
  fs.writeFileSync(new URL("./schema-bizzi-db.sql", import.meta.url), rows.map((r) => r.sql).join("\n\n"));
  const leftBefore = await runPasses(tgt, before, "structure");
  fs.writeFileSync(new URL("./after-data.json", import.meta.url), JSON.stringify(after));
  for (const f of leftBefore) console.log("ECHEC", f.grp, f.k, "->", f.error);
  console.log(`structure : ${rows.length} instructions, ${leftBefore.length} en echec ; ${after.length} (cles etrangeres + triggers) reportees apres les donnees`);
  await src.end();
  await tgt.end();
}

async function data() {
  const [src, tgt] = [await connect(env.SOURCE_URL), await connect(env.TARGET_URL)];
  const list = await tables(src);
  const { rows: fks } = await tgt.query(
    `select conrelid::regclass::text as t, conname from pg_constraint where contype = 'f' and connamespace = 'public'::regnamespace`,
  );
  for (const fk of fks) await tgt.query(`alter table ${fk.t} drop constraint ${q(fk.conname)}`);
  for (const table of list) await tgt.query(`alter table public.${q(table)} disable trigger user`);
  for (const table of list) {
    const cols = await columns(src, table);
    const build = cols.map((c) => `${q(c.attname)}::text`).join(", ");
    const { rows } = await src.query(`select json_build_array(${build}) as r from public.${q(table)}`);
    await tgt.query(`truncate public.${q(table)} cascade`);
    const values = rows.map((r) => r.r);
    for (let i = 0; i < values.length; i += 500) {
      const batch = values.slice(i, i + 500);
      const select = cols.map((c, idx) => `(r->>${idx})::${c.type}`).join(", ");
      const overriding = cols.some((c) => c.attidentity === "a") ? " overriding system value" : "";
      await tgt.query(
        `insert into public.${q(table)} (${cols.map((c) => q(c.attname)).join(", ")})${overriding}
         select ${select} from json_array_elements($1::json) r`,
        [JSON.stringify(batch)],
      );
    }
    for (const c of cols.filter((c) => c.attidentity)) {
      await tgt.query(`select setval(pg_get_serial_sequence($1, $2), coalesce((select max(${q(c.attname)}) from public.${q(table)}), 0) + 1, false)`, [`public.${table}`, c.attname]);
    }
    console.log(`${table}: ${values.length}`);
  }
  for (const table of list) await tgt.query(`alter table public.${q(table)} enable trigger user`);
  const after = JSON.parse(fs.readFileSync(new URL("./after-data.json", import.meta.url), "utf8"));
  const fkAndTriggers = after.map((s) => ({ ...s, sql: s.grp === 21 ? s.sql.replace(/^CREATE TRIGGER/i, "CREATE OR REPLACE TRIGGER") : s.sql }));
  const left = await runPasses(tgt, fkAndTriggers, "cles etrangeres + triggers");
  for (const f of left) console.log("ECHEC", f.k, "->", f.error);
  await src.end();
  await tgt.end();
}

async function verify() {
  const [src, tgt] = [await connect(env.SOURCE_URL), await connect(env.TARGET_URL)];
  const COUNT = `select c.relname as t, (xpath('/row/n/text()', query_to_xml(format('select count(*) as n from public.%I', c.relname), false, true, '')))[1]::text::int as n
    from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'r' order by 1`;
  const OBJ = `select (select count(*) from pg_proc p where p.pronamespace = 'public'::regnamespace) as fonctions,
    (select count(*) from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind = 'v') as vues,
    (select count(*) from pg_trigger t join pg_class c on c.oid = t.tgrelid where c.relnamespace = 'public'::regnamespace and not t.tgisinternal) as triggers,
    (select count(*) from pg_policies where schemaname = 'public') as policies,
    (select count(*) from pg_constraint where connamespace = 'public'::regnamespace) as contraintes,
    (select count(*) from pg_indexes where schemaname = 'public') as index`;
  const [a, b] = [(await src.query(COUNT)).rows, (await tgt.query(COUNT)).rows];
  const target = Object.fromEntries(b.map((r) => [r.t, r.n]));
  let diff = 0;
  for (const r of a) {
    if (EXCLUDED_TABLES.has(r.t)) continue;
    if (target[r.t] !== r.n) {
      diff += 1;
      console.log(`DIFFERENCE ${r.t}: source ${r.n}, cible ${target[r.t]}`);
    }
  }
  console.log(`tables comparees : ${a.length - EXCLUDED_TABLES.size}, differences : ${diff}`);
  console.log("objets source", (await src.query(OBJ)).rows[0]);
  console.log("objets cible ", (await tgt.query(OBJ)).rows[0]);
  await src.end();
  await tgt.end();
}

await ({ schema, data, verify }[mode] || (() => console.log("mode: schema | data | verify")))();
